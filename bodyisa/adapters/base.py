"""The interface consumed by the synchronous Runtime; no concrete body imports."""
from typing import Protocol, Any
from bodyisa.core import StateSnapshot, Instruction, CapabilityRegistry, PoseRegistry


class BodyAdapter(Protocol):
    identity: dict
    dt: float
    mass: float
    capabilities: CapabilityRegistry
    poses: PoseRegistry
    reference: Any
    supported_instructions: tuple[Instruction, ...]

    def snapshot(self) -> StateSnapshot: ...
    def prepare(self, instruction: Instruction) -> tuple: ...
    def step(self, elapsed: float, tracking: bool = False) -> None: ...
    def use_stand(self) -> None: ...
    def tracking_metrics(self, state: StateSnapshot, time: float) -> dict: ...
    def context_identity(self) -> dict: ...
    def initialize_nominal(self, joint_delta, max_delta: float): ...
    def create_observer(self, config: dict): ...
    def evidence_identity(self, physical: dict, semantic: dict, entry: dict) -> dict: ...
    def close(self) -> None: ...
